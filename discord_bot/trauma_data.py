def _load_psychological_traumas() -> dict[int, Trauma]:
    module_dir = Path(__file__).resolve().parent
    candidates = (
        module_dir.parent / "Психологические травмы.txt",
        module_dir / "PSYCHOLOGICAL_TRAUMAS_SOURCE.txt",
    )
    source = next((candidate for candidate in candidates if candidate.is_file()), None)
    if source is None:
        return {}
    text = source.read_text(encoding="utf-8")
    pattern = re.compile(
        r"Психологическая травма:\s*(.+?)\s*\((\d{2})\)\s*\n"
        r"Описание\s*\n(.*?)\s*\nШтрафы\s*\n(.*?)\s*\nВремя действия\s*\n(.*?)(?=\n\s*🧠|\Z)",
        re.DOTALL,
    )
    result: dict[int, Trauma] = {}
    for name, code, description, penalties, duration in pattern.findall(text):
        number = int(code)
        result[number] = t(
            number,
            name.strip(),
            " ".join(description.split()),
            " ".join(penalties.split()),
            " ".join(duration.split()),
        )
    return result


MENTAL_TRAUMAS: dict[int, Trauma] = _load_psychological_traumas()
SOCIAL_TRAUMAS: dict[int, Trauma] = MENTAL_TRAUMAS
